func readNativeFileMap(t *testing.T, h string) *FileMap {
	t.Helper()
	data, err := hex.DecodeString(h)
	if err != nil {
		t.Fatal(err)
	}
	d, err := Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	m, err := d.FileMap()
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func resolvedEntries(m *FileMap) map[string]struct {
	Display string
	Flags   uint32
	Owner   []IdentityAttribute
} {
	out := make(map[string]struct {
		Display string
		Flags   uint32
		Owner   []IdentityAttribute
	})
	for _, entry := range m.Entries {
		out[entry.Name] = struct {
			Display string
			Flags   uint32
			Owner   []IdentityAttribute
		}{entry.DisplayName, entry.Flags, m.Identities[entry.Identity]}
	}
	return out
}

func TestNativeFileMapReplacementAndRemoval(t *testing.T) {
	for _, replacement := range []bool{true, false} {
		name, expected := "remove", nativeTimeZoneRemoval
		if replacement {
			name, expected = "replace", nativeTimeZoneReplacement
		}
		t.Run(name, func(t *testing.T) {
			before := readNativeFileMap(t, nativeTimeZoneBefore)
			want := readNativeFileMap(t, expected)
			if len(before.Entries) != 4 {
				t.Fatal("invalid native input")
			}
			found := false
			for i, entry := range before.Entries {
				if entry.Name != "tzautoupdate.dat" {
					continue
				}
				found = true
				if replacement {
					changed := false
					for j, attr := range before.Identities[entry.Identity] {
						if attr.Name == "Version" && attr.Namespace == "" && attr.Value == "10.0.26100.9278" {
							before.Identities[entry.Identity][j].Value = "10.0.26100.9711"
							changed = true
						}
					}
					if !changed {
						t.Fatal("old native owner version absent")
					}
				} else {
					before.Entries = append(before.Entries[:i], before.Entries[i+1:]...)
				}
				break
			}
			if !found {
				t.Fatal("native target absent")
			}
			encoded, err := before.Marshal()
			if err != nil {
				t.Fatal(err)
			}
			d, err := Parse(encoded)
			if err != nil {
				t.Fatal(err)
			}
			got, err := d.FileMap()
			if err != nil {
				t.Fatal(err)
			}
			if got.Path != want.Path || got.RootSelector != want.RootSelector || !reflect.DeepEqual(resolvedEntries(got), resolvedEntries(want)) {
				t.Fatal("portable edit disagrees with native ownership, sibling preservation or metadata")
			}
			if len(got.Identities) != len(want.Identities) {
				t.Fatal("stale owner survived pruning")
			}
		})
	}
}

