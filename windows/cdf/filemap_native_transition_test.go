func TestNativeFileMapDirectoryOwnershipReplacement(t *testing.T) {
	input := readNativeFileMap(t, nativeFeatureConfigBefore)
	found := false
	for i := range input.Entries {
		if input.Entries[i].Name != "." {
			continue
		}
		if found {
			t.Fatal("multiple directory records")
		}
		found = true
		owner := append([]IdentityAttribute(nil), input.Identities[input.Entries[i].Identity]...)
		changed := false
		for j := range owner {
			if owner[j].Name == "Version" {
				if owner[j].Value != "10.0.26100.9278" {
					t.Fatal("unexpected old owner")
				}
				owner[j].Value = "10.0.26100.9549"
				changed = true
			}
		}
		if !changed {
			t.Fatal("missing owner version")
		}
		input.Identities = append(input.Identities, owner)
		input.Entries[i].Identity = uint32(len(input.Identities) - 1)
	}
	if !found {
		t.Fatal("missing directory record")
	}
	data, err := input.Marshal()
	if err != nil {
		t.Fatal(err)
	}
	doc, err := Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	got, err := doc.FileMap()
	if err != nil {
		t.Fatal(err)
	}
	want := readNativeFileMap(t, nativeFeatureConfigDirectoryReplacement)
	if got.Path != want.Path || got.RootSelector != want.RootSelector || !reflect.DeepEqual(resolvedEntries(got), resolvedEntries(want)) {
		t.Fatal("directory owner replacement or preserved child ownership differs from native")
	}
}
