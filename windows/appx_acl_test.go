package windows

import (
	"bytes"
	"encoding/binary"
	"encoding/hex"
	"testing"
)

func TestAppxPackageACL(t *testing.T) {
	// Native WindowsApps inheritable SYSTEM/OI|CI and Administrators/CI grants.
	parent, _ := hex.DecodeString("020034000200000000031400ff011f0001010000000000051200000000021800a900120001020000000000052000000020020000")
	root, err := AppxPackageACL(parent, "Microsoft.WindowsTerminal_8wekyb3d8bbwe", "root")
	if err != nil {
		t.Fatal(err)
	}
	_, aces, err := ParseACL(root)
	if err != nil {
		t.Fatal(err)
	}
	// Captured Windows 11 Terminal native conditional ACE, not generated by test helper.
	want, _ := hex.DecodeString("09039400a90012000102000000000005200000002102000061727478f81c000000570049004e003a002f002f0053005900530041005000500049004400104e0000004d006900630072006f0073006f00660074002e00570069006e0064006f00770073005400650072006d0069006e0061006c005f003800770065006b0079006200330064003800620062007700650086000000")
	if !bytes.Equal(aces[0].Data, want) {
		t.Fatalf("native condition mismatch: %x", aces[0].Data)
	}
	wantSID, _ := hex.DecodeString("010800000000000f03000000a171c34a86ba0f5800ff245b8b20e329db44d404c8979ed94f7568ab")
	if !bytes.Equal(aces[1].SID, wantSID) {
		t.Fatalf("native capability mismatch: %x", aces[1].SID)
	}
	file, err := AppxPackageACL(parent, "Microsoft.WindowsTerminal_8wekyb3d8bbwe", "file")
	if err != nil {
		t.Fatal(err)
	}
	_, files, _ := ParseACL(file)
	if len(files) != 4 || files[0].Flags != 16 || files[2].Mask&0x20 != 0 || files[3].Flags != 16 {
		t.Fatalf("file inheritance: %+v", files)
	}
	if aces[3].Flags != 19 || aces[4].Flags != 18 {
		t.Fatal("directory inheritance lost")
	}
	for _, family := range []string{"", "../bad_x", "a_b_c", "a_\x00"} {
		if _, err := AppxPackageACL(parent, family, "root"); err == nil {
			t.Fatal("invalid family accepted")
		}
	}
	bad := append([]byte(nil), parent...)
	bad[9] |= 4
	if _, err := AppxPackageACL(bad, "Example_abc", "root"); err == nil {
		t.Fatal("unsupported inherited flags accepted")
	}
	bad = append([]byte(nil), parent...)
	binary.LittleEndian.PutUint16(bad[10:], 65535)
	if _, err := AppxPackageACL(bad, "Example_abc", "root"); err == nil {
		t.Fatal("malformed parent accepted")
	}
}
