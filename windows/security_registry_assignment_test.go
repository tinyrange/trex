func TestAssignRegistrySecurityRejectsUnestablishedPolicy(t *testing.T) {
	old, _ := CompileSDDL("O:SYG:SYD:P(A;;KA;;;SY)")
	valid := bytes.Clone(old)
	for _, tc := range []struct {
		name             string
		current, request []byte
		info             uint32
	}{
		{"partial-update", old, valid, 4},
		{"wrong-protection", old, valid, 0x3000000f},
		{"truncated-old", old[:19], valid, 0x9000000f},
		{"truncated-request", old, valid[:19], 0x9000000f},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := AssignRegistrySecurity(tc.current, tc.request, tc.info); err == nil {
				t.Fatal("accepted invalid policy")
			}
		})
	}
	for _, text := range []string{"O:SYG:SYD:NO_ACCESS_CONTROL", "D:P(A;;KA;;;SY)", "O:SYG:SYD:P(A;;KA;;;SY)S:(ML;;0x1;;;LW)(ML;;0x1;;;LW)"} {
		request, err := CompileSDDL(text)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := AssignRegistrySecurity(old, request, 0x9000001f); err == nil {
			t.Fatalf("accepted unsupported %s", text)
		}
	}
	malformed := bytes.Clone(valid)
	malformed[1] = 1
	if _, err := AssignRegistrySecurity(old, malformed, 0x9000000f); err == nil {
		t.Fatal("accepted resource-manager controls")
	}
	// Both returned descriptors and parsed components must be owned.
	got, err := AssignRegistrySecurity(old, valid, 0x9000000f)
	if err != nil {
		t.Fatal(err)
	}
	saved := bytes.Clone(got)
	for i := range valid {
		valid[i] = 0
	}
	for i := range old {
		old[i] = 0
	}
	if !bytes.Equal(got, saved) {
		t.Fatal("result aliases input")
	}
}
