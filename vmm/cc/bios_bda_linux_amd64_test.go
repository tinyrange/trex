//go:build linux && amd64

package cc

import (
	"context"
	"encoding/binary"
	"testing"
	"time"

	"github.com/tinyrange/trex/vmm"
	"j5.nz/cc/hypervisor"
)

// OS/2 VDMs intercept private ports. These services must return from actual
// ROM instructions, using the caller's BDA, with no host-service I/O.
func TestBIOSBDAQueriesNative(t *testing.T) {
	requireKVM(t)
	data := make([]byte, 512)
	code := []byte{
		0xc7, 0x06, 0x13, 0x04, 0x7f, 0x02, // BDA conventional memory = 639
		0xc7, 0x06, 0x10, 0x04, 0x34, 0x12, // arbitrary equipment word
		0xb8, 0x23, 0x01, 0x8e, 0xd8, // nonzero DS must be preserved
		0xf9, 0xcd, 0x12, 0x2e, 0xa3, 0x00, 0x80,
		0x9c, 0x58, 0x2e, 0xa3, 0x02, 0x80,
		0x8c, 0xd8, 0x2e, 0xa3, 0x04, 0x80,
		0xcd, 0x11, 0x2e, 0xa3, 0x06, 0x80,
		0x31, 0xc0, 0x8e, 0xd8,
		0xb8, 0x00, 0x01, 0xcd, 0x16, 0x9c, 0x58, 0xa3, 0x08, 0x80,
		// Wrap-around ring: head=3c, tail=1e, enhanced up-arrow word.
		0xc7, 0x06, 0x1a, 0x04, 0x3c, 0x00,
		0xc7, 0x06, 0x1c, 0x04, 0x1e, 0x00,
		0xc7, 0x06, 0x3c, 0x04, 0xe0, 0x48,
		0xb8, 0x00, 0x11, 0xcd, 0x16, 0xa3, 0x0a, 0x80,
		0x9c, 0x58, 0xa3, 0x0c, 0x80,
		0xb8, 0x00, 0x01, 0xcd, 0x16, 0xa3, 0x0e, 0x80,
		0xb8, 0x00, 0x10, 0xcd, 0x16, 0xa3, 0x10, 0x80,
		0xa1, 0x1a, 0x04, 0xa3, 0x12, 0x80,
		0xb8, 0x00, 0x11, 0xcd, 0x16, 0x9c, 0x58, 0xa3, 0x14, 0x80,
		0xc6, 0x06, 0x17, 0x04, 0x23, 0xc6, 0x06, 0x18, 0x04, 0x45,
		0xb8, 0x00, 0x12, 0xcd, 0x16, 0xa3, 0x16, 0x80,
		0xb0, 0x42, 0xe6, 0xf2, 0xeb, 0xfe,
	}
	copy(data, code)
	binary.LittleEndian.PutUint16(data[510:], 0xaa55)
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	cpu, err := hypervisor.NewX86(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer cpu.Close()
	ram, err := cpu.MapRAM(0, 16<<20)
	if err != nil {
		t.Fatal(err)
	}
	p, err := newPC(cpu, ram, vmm.Disk{Device: testBlock(t, data)}, time.Now)
	if err != nil {
		t.Fatal(err)
	}
	for {
		ex, err := p.run(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if ex.Reason == 0 {
			continue
		}
		if ex.Reason != hypervisor.X86ExitIO {
			t.Fatalf("unexpected exit %+v", ex)
		}
		if ex.Port == 0xf2 {
			break
		}
		if ex.Port == biosPort || ex.Port == videoRequestPort || ex.Port == videoDataPort {
			t.Fatalf("BDA query escaped ROM through host trap: %+v", ex)
		}
		if err = p.handleIO(ex); err != nil {
			t.Fatal(err)
		}
	}
	word := func(o int) uint16 { return binary.LittleEndian.Uint16(ram[0x8000+o:]) }
	if word(0) != 639 || word(2)&1 != 1 || word(4) != 0x123 || word(6) != 0x1234 {
		t.Fatalf("memory/equipment/DS/flags: %x", ram[0x8000:0x8008])
	}
	if word(8)&0x40 == 0 || word(10) != 0x48e0 || word(12)&0x40 != 0 || word(14) != 0x4800 || word(16) != 0x48e0 || word(18) != 0x1e || word(20)&0x40 == 0 || word(22) != 0x4523 {
		t.Fatalf("keyboard ring/status/compatibility: %x", ram[0x8008:0x8018])
	}
	r, err := cpu.Registers()
	if err != nil {
		t.Fatal(err)
	}
	if r.Rsp != 0x7c00 {
		t.Fatalf("ROM stack leaked: %#x", r.Rsp)
	}
}
