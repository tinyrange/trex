var punchEBCDIC = func() [4096]uint16 {
	var codes [4096]uint16
	for c, rows := range ebcdicPunch {
		codes[rows] = uint16(c) + 1
	}
	return codes
}()

func (u *UnitRecord) diagnosticWrite(data []byte) ([]byte, int, byte) {
	reader := u.cardPeer
	if reader == nil {
		return u.reject()
	}
	x := u.css.bydev[reader.devno]
	if x.working() || x.deAt != 0 {
		return u.reject()
	}
	if !reader.diagReady {
		clear(reader.diagColumns[:])
		if len(reader.cards) > 0 {
			card := reader.cards[0]
			if len(card) == 160 {
				copy(reader.diagColumns[:], card)
			} else {
				for i, c := range card {
					rows := ebcdicPunch[c]
					reader.diagColumns[2*i], reader.diagColumns[2*i+1] = byte(rows>>6), byte(rows&0x3f)
				}
			}
		}
	}
	n := min(len(data), 160)
	for i, x := range data[:n] {
		reader.diagColumns[i] = x & 0x3f
	}
	reader.diagReady = true
	reader.last = rdNone
	u.chanT = urControlXfr + time.Duration(n)*urByte
	return nil, n, usCE | usDE
}

func readCardColumns(columns []byte, binaryMode bool) ([]byte, byte) {
	if binaryMode {
		return append([]byte(nil), columns...), 0
	}
	card := make([]byte, 80)
	var sense byte
	for i := range card {
		rows := uint16(columns[2*i])<<6 | uint16(columns[2*i+1])
		code := punchEBCDIC[rows]
		if code == 0 {
			sense = 0x08 // data check in the read translator
		}
		card[i] = byte(code - 1)
	}
	return card, sense
}
