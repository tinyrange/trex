package starlarkfrontend

import "testing"

func TestWindowsMemoryInventories(t *testing.T) {
	architectureScript(t, `
load("@stdlib//windows:memory.star", "read_vads", "read_threads", "read_handle_table", "read_file_handles", "read_drivers")
def check(value, message):
    if not value:
        fail(message)
def run():
    b = binary.builder()
    b.reserve(32768)
    vad_layout = {"start_vpn":(0,"uint",4), "end_vpn":(4,"uint",4), "parent":(8,"uint",4), "left":(12,"uint",4), "right":(16,"uint",4)}
    b.patch_u32le(128,10)
    b.patch_u32le(132,19)
    b.patch_u32le(140,160)
    b.patch_u32le(160,2)
    b.patch_u32le(164,4)
    b.patch_u32le(168,128)
    space = windows.memory_image(b.file())
    vads = read_vads(space,128,vad_layout)
    check(vads["complete"] and len(vads["value"])==2 and vads["value"][0]["end"]==20<<12,"VAD ranges")
    check(read_vads(space,0,vad_layout)["complete"],"empty VAD tree")
    check(read_vads(space,128,vad_layout,maximum=1)["fault"]["kind"]=="limit","VAD bound")
    b.patch_u32le(164,10)
    check(not read_vads(windows.memory_image(b.file()),128,vad_layout)["complete"],"overlap accepted")
    b.patch_u32le(164,4)
    b.patch_u32le(168,0)
    check(not read_vads(windows.memory_image(b.file()),128,vad_layout)["complete"],"bad parent accepted")
    b.patch_u32le(168,128)
    b.patch_u32le(172,128)
    check(not read_vads(windows.memory_image(b.file()),128,vad_layout)["complete"],"cycle accepted")
    b.patch_u32le(16,32)
    b.patch_u32le(20,32)
    b.patch_u32le(32,16)
    b.patch_u32le(36,16)
    b.patch_u32le(40,10)
    b.patch_u32le(44,20)
    space = windows.memory_image(b.file())
    thread_layout={"pid":(8,"uint",4),"tid":(12,"uint",4)}
    check(read_threads(space,16,thread_layout,0,10,expected_count=1)["complete"],"thread inventory")
    check(not read_threads(space,16,thread_layout,0,11)["complete"],"wrong owner accepted")
    check(not read_threads(space,16,thread_layout,0,10,expected_count=2)["complete"],"wrong thread count")
    # One live handle in a level-zero table; remaining slots are free.
    table_layout={"table_code":(0,"uint",4),"next_handle":(4,"uint",4),"count":(8,"uint",4)}
    b.patch_u32le(256,4096)
    b.patch_u32le(260,16)
    b.patch_u32le(264,1)
    b.patch_u32le(4104,16385)
    b.patch_u32le(4108,0x123)
    # Object header -> type descriptor named File -> body with IO_TYPE_FILE.
    b.patch_u32le(16392,20000)
    b.patch_u16le(20000,8)
    b.patch_u16le(20002,8)
    b.patch_u32le(20004,21000)
    for i, value in enumerate([70,105,108,101]):
        b.patch_u16le(21000+i*2,value)
    b.patch_u16le(16408,5)
    space = windows.memory_image(b.file())
    handles=read_handle_table(space,256,table_layout)
    check(handles["complete"] and handles["value"][0]["handle"]==4,"level-zero handles")
    files=read_file_handles(space,handles,{"type":(8,"uint",4)},{"name":(0,"unicode",8)},{"type":(0,"uint",2)},24)
    check(files["complete"] and len(files["value"])==1 and files["value"][0]["access"]==0x123,"file type filter")
    check(not read_handle_table(space,256,table_layout,maximum=1)["complete"],"free slots must count toward bound")
    b.patch_u16le(16408,4)
    check(not read_file_handles(windows.memory_image(b.file()),handles,{"type":(8,"uint",4)},{"name":(0,"unicode",8)},{"type":(0,"uint",2)},24)["complete"],"file discriminator")
    b.patch_u32le(264,2)
    check(not read_handle_table(windows.memory_image(b.file()),256,table_layout)["complete"],"wrong handle count")
    b.patch_u32le(264,1)
    b.patch_u32le(256,8193)
    b.patch_u32le(8192,4096)
    check(read_handle_table(windows.memory_image(b.file()),256,table_layout)["complete"],"one-level handles")
    b.patch_u32le(256,12290)
    b.patch_u32le(12288,8192)
    check(read_handle_table(windows.memory_image(b.file()),256,table_layout)["complete"],"two-level handles")
    b.patch_u32le(8192,4097)
    check(not read_handle_table(windows.memory_image(b.file()),256,table_layout)["complete"],"unaligned leaf")
    b.patch_u32le(8192,4096)
    sparse=windows.memory_image(b.file(),ranges=[(256,256,12),(12288,12288,4)])
    check(read_handle_table(sparse,256,table_layout)["fault"]["kind"]=="not-captured","missing table page")
    # Driver loader range rounds a small PE image up to a page.
    b.patch_u32le(40,24000)
    b.patch_u32le(44,4096)
    b.patch_u16le(24000,0x5a4d)
    b.patch_u32le(24060,64)
    b.patch_u32le(24064,0x4550)
    b.patch_u16le(24068,0x14c)
    b.patch_u16le(24088,0x10b)
    b.patch_u32le(24144,3000)
    module_layout={"base":(8,"uint",4),"size":(12,"uint",4)}
    drivers=read_drivers(windows.memory_image(b.file()),16,module_layout)
    check(drivers["complete"] and drivers["value"][0]["pe"]["complete"],"rounded driver size")
    b.patch_u32le(24144,5000)
    drivers=read_drivers(windows.memory_image(b.file()),16,module_layout)
    check(drivers["complete"] and not drivers["value"][0]["pe"]["complete"],"driver size mismatch evidence")
    sparse=windows.memory_image(b.file(),ranges=[(16,16,32)])
    drivers=read_drivers(sparse,16,module_layout)
    check(drivers["complete"] and drivers["value"][0]["pe"]["fault"]["kind"]=="not-captured","missing header must not hide driver")
run()
`)
}
