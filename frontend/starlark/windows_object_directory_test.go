package starlarkfrontend

import "testing"

func TestNativeObjectDirectoryOwnership(t *testing.T) {
	architectureScript(t, `
load("@stdlib//windows/selfreg:win32.star", "kernel32_plugin")
load("@stdlib//windows/selfreg:objects.star", "object_directories_plugin")
load("@stdlib//windows/emulation:abi.star", "object_attributes_layout", "counted_string_layout")
def exercise(arch):
    m=emulator.machine(architecture=arch,code=b"\xc3")
    k=kernel32_plugin()
    plugin=object_directories_plugin(k,{"\\RPC Control":0x20001,"\\RPC Control\\Child":1})
    m.use([k,plugin])
    fn=m.resolve_export("ntdll.dll",name="NtOpenDirectoryObject")
    close=m.resolve_export("ntdll.dll",name="NtClose")
    query=m.resolve_export("ntdll.dll",name="NtQuerySecurityObject")
    winclose=m.resolve_export("kernel32.dll",name="CloseHandle")
    oa=object_attributes_layout(m.pointer_size)
    us=counted_string_layout(m.pointer_size)
    attrs=m.allocate(size=oa["Size"])
    string=m.allocate(size=us["Size"])
    out=m.allocate(value=b"X"*16)
    m.write_u32le(attrs,oa["Size"])
    m.write_pointer(attrs+oa["ObjectName"],string)
    def attempt(name,access,status,root=0,flags=0):
        raw=binary.encode(name,encoding="utf16le")
        buffer=m.allocate(value=binary.encode(name+"JUNK",encoding="utf16le"))
        m.write_u16le(string,len(raw))
        m.write_u16le(string+2,len(raw))
        m.write_pointer(string+us["Buffer"],buffer)
        m.write_pointer(attrs+oa["RootDirectory"],root)
        m.write_u32le(attrs+oa["Attributes"],flags)
        m.write(out,b"X"*16)
        before=len(plugin.state["opens"])
        r=m.call(fn,args=[out,access,attrs])
        if r.reason!="return" or r.value!=status: fail("open result",name,r)
        if status:
            if m.read(out,16)!=b"X"*16 or len(plugin.state["opens"])!=before: fail("failed open changed output/ownership")
            return 0
        if m.read(out+m.pointer_size,16-m.pointer_size)!=b"X"*(16-m.pointer_size): fail("native handle width")
        return m.read_pointer(out)
    first=attempt("\\RPC Control",0x20001,0)
    second=attempt("\\RPC Control",1,0)
    if first==second: fail("opens share handle")
    required=m.allocate(value=b"Z"*4)
    m.write(out,b"X"*16)
    r=m.call(query,args=[second,0x17,out,16,required])
    if r.reason!="return" or r.value!=0xc0000022 or m.read(out,16)!=b"X"*16 or m.read(required,4)!=b"Z"*4: fail("security query ignored READ_CONTROL")
    r=m.call(query,args=[first,0x17,out,16,required])
    if r.reason!="plugin" or m.read(out,16)!=b"X"*16 or m.read(required,4)!=b"Z"*4: fail("missing descriptor was fabricated")
    attempt("\\RPC Control",4,0xc0000022)
    attempt("\\Missing",1,0xc0000034)
    attempt("\\rpc control",1,0xc0000034)
    attempt("\\rpc control",1,0,flags=0x40)
    attempt("Child",1,0,root=first)
    attempt("Child",1,0xc0000008,root=0x123456)
    r=m.call(close,args=[first])
    if r.reason!="return" or r.value: fail("owned close")
    attempt("Child",1,0xc0000008,root=first)
    r=m.call(query,args=[first,0x17,out,16,required])
    if r.reason!="return" or r.value!=0xc0000008: fail("security query accepted closed handle")
    r=m.call(winclose,args=[first])
    if r.reason!="return" or r.value: fail("double close succeeded")
    if plugin.state["handles"][second]["closed"]: fail("closing one handle closed independent open")
    attempt("\\RPC Control",1,0)
    m.write(out,b"X"*16)
    m.write_u32le(attrs,oa["Size"]-4)
    r=m.call(fn,args=[out,1,attrs])
    if r.reason!="return" or r.value!=0xc000000d or m.read(out,16)!=b"X"*16: fail("bad attributes not atomic")
    m.write_u32le(attrs,oa["Size"])
    m.write_u16le(string,3)
    r=m.call(fn,args=[out,1,attrs])
    if r.reason!="return" or r.value!=0xc000000d: fail("odd counted name length")
    m.write_u32le(attrs+oa["Attributes"],0x200)
    r=m.call(fn,args=[out,1,attrs])
    if r.reason!="plugin" or m.read(out,16)!=b"X"*16: fail("unsupported attributes accepted")
exercise("x86")
exercise("amd64")
`)
}
