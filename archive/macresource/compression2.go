// dcmp2 stores two-byte table references, optionally mixed with literals under
// an MSB-first eight-bit tag. Odd decoded lengths store the last byte literally.
// Layout and dictionary: https://formats.kaitai.io/dcmp_2/.
func (d *resourceDecoder) tableWords(parameters []byte) error {
	flags := parameters[3]
	if flags & ^byte(3) != 0 {
		return fmt.Errorf("unknown dcmp2 flags %02x", flags)
	}
	table := dcmp2Words[:]
	if flags&1 != 0 {
		table = make([]uint16, int(parameters[2])+1)
		b, err := d.take(2 * len(table))
		if err != nil {
			return err
		}
		for i := range table {
			table[i] = binary.BigEndian.Uint16(b[i*2:])
		}
	}
	end := len(d.input) - (d.limit & 1)
	var tag byte
	for unit := 0; d.pos < end; unit++ {
		if flags&2 != 0 && unit%8 == 0 {
			var err error
			tag, err = d.byte()
			if err != nil {
				return err
			}
			if d.pos == end {
				return fmt.Errorf("empty tagged block")
			}
		}
		if flags&2 != 0 && tag&(0x80>>uint(unit%8)) == 0 {
			if end-d.pos < 2 {
				return fmt.Errorf("truncated word literal")
			}
			if err := d.literal(2, false); err != nil {
				return err
			}
		} else {
			index, err := d.byte()
			if err != nil {
				return err
			}
			if int(index) >= len(table) {
				return fmt.Errorf("table index %d outside dictionary", index)
			}
			if err := d.word(table[index]); err != nil {
				return err
			}
		}
	}
	if d.limit&1 != 0 {
		return d.literal(1, false)
	}
	return nil
}

